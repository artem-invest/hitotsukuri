function hash(s) { let n = 0; for (const c of s) n = (n * 31 + c.charCodeAt(0)) >>> 0; return n; }
const FALLBACK = ["#d0472f", "#3f6fc4", "#3a9a62", "#9a5bb3", "#c7772a", "#2b8f8f", "#b0456e", "#5c6bc0"];

// {sym: 記号, color: 色, known: 表があるか}
export function lineStyle(name) {
  const s = S[name];
  if (s) return { sym: s[0] || name.replace(/^(JR|JR東日本|JR東海|メトロ|都営) /, "")[0], color: s[1], known: true };
  const bare = name.replace(/^\S+ /, "");
  return { sym: bare[0], color: FALLBACK[hash(name) % FALLBACK.length], known: false };
}

